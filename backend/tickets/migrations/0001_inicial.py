"""App ``tickets``: ``ticket``, ``aviso_ticket`` y ``ticket_evento`` (ADR-023, puntos 1, 2 y 4; ADR-024, punto 1).

``ticket`` y ``aviso_ticket`` los crea Django con sus CHECK y únicos parciales
(ver ``tickets.models``). ``ticket_evento`` se crea con SQL explícito y modelo
``managed=False``, con el patrón de ``bitacora`` (ADR-010):

- sin FK (ni hacia ``usuario`` ni hacia ``ticket``): una FK o el trigger
  ``BEFORE TRUNCATE`` impedirían el vaciado de las pruebas ``transaction=True``;
- CHECK: estados y motivos de la lista cerrada, autor ``usuario`` si y solo si
  hay ``autor_id``, motivo si y solo si el estado nuevo es ``cerrado`` y un
  estado nuevo distinto del anterior;
- triggers que rechazan UPDATE, DELETE (por fila) y TRUNCATE (por sentencia).
  Son defensa en profundidad: la barrera principal es que la aplicación no
  ofrece forma de editar ni borrar (``comun.solo_insercion``).
"""
